// Build the mini program's shared libs from the web sources, so parsing/diagnosis stay identical:
//   miniprogram/libs/core.js    ← public/js/core.js wrapped as a CommonJS module (XLSX required, no DOM)
//   miniprogram/libs/xlsx.full.min.js, qrcode.js ← vendored libraries
// Usage: node scripts/build_miniprogram.js [miniprogram dir]   (default ../miniprogram)
const fs = require('fs');
const path = require('path');
const WEB = path.join(__dirname, '..');
const MP = path.resolve(process.argv[2] || path.join(WEB, '..', 'miniprogram'));
const LIBS = path.join(MP, 'libs');
fs.mkdirSync(LIBS, { recursive: true });

const core = fs.readFileSync(path.join(WEB, 'public/js/core.js'), 'utf8').replace(/^"use strict";\n/, '');
const out = `"use strict";
// GENERATED by web/scripts/build_miniprogram.js from web/public/js/core.js — edit the web source, then rebuild.
const XLSX = require('./xlsx.full.min.js');
${core}
module.exports = {
  ingestAirports, readWorkbook, buildFlights, resolveAirport, parseDate, parseTime, ymd, hav, demoRows, rowStatus, rkey,
  setRaw(rows) { RAW = rows; }, setSource(s) { SOURCE = s; },
  get AP() { return AP; }, get ZH() { return ZH; }, get ZHKEYS() { return ZHKEYS; }, get NAMES() { return NAMES; }, manual,
};
`;
fs.writeFileSync(path.join(LIBS, 'core.js'), out);
fs.copyFileSync(path.join(WEB, 'public/vendor/xlsx.full.min.js'), path.join(LIBS, 'xlsx.full.min.js'));
fs.copyFileSync(path.join(WEB, 'public/vendor/qrcode.min.js'), path.join(LIBS, 'qrcode.js'));
console.log('mini program libs →', LIBS);
